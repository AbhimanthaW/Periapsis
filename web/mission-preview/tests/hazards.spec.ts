import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

const rover = '/#monitor/rover/43/hazards'
const next = (page: Page) => page.getByRole('button', { name: 'Next update' }).click()
const route = (page: Page, id: 'A' | 'B') => page.locator('article').filter({
  has: page.getByRole('button', { name: new RegExp('Route ' + id + ' ·') }),
})

test('caution, minor updates, closure, approval and recovery preserve operator control', async ({ page }) => {
  await page.goto(rover)
  await expect(route(page, 'A')).toContainText('ACTIVE PLAN')
  await next(page)
  await expect(page.getByRole('status')).toContainText('Review a detour')
  await expect(route(page, 'A')).toContainText('42 m')
  await expect(route(page, 'B')).toContainText('REVIEW ADVISED')
  await expect(page.getByTestId('dust-footprint')).toBeVisible()
  await next(page)
  await expect(route(page, 'A')).toContainText('ACTIVE PLAN')
  await next(page)
  await expect(page.getByRole('status')).toHaveText('Active route blocked')
  await expect(route(page, 'A')).toContainText('ACTIVE PLAN')
  await expect(route(page, 'A')).toContainText('Crosses the active northern corridor closure')
  await page.getByRole('button', { name: /Route A ·/ }).click()
  await expect(page.getByRole('button', { name: 'Approve route A' })).toBeDisabled()
  await page.getByRole('button', { name: /Route B ·/ }).click()
  await page.getByRole('button', { name: 'Approve route B' }).click()
  await expect(route(page, 'B')).toContainText('ACTIVE PLAN')
  await expect(page.getByText('Approved · Route B', { exact: true })).toBeVisible()
  await next(page)
  await expect(page.getByRole('status')).toHaveText('Station data stale')
  await page.getByRole('button', { name: 'Hold position' }).click()
  await expect(page.getByRole('button', { name: 'Resume B' })).toBeDisabled()
  await expect(page.getByTestId('dust-footprint')).toHaveClass(/footprint-stale/)
  await next(page)
  await expect(page.getByTestId('dust-footprint')).toHaveCount(0)
  await expect(route(page, 'B')).toContainText('ACTIVE PLAN')
  await page.getByRole('button', { name: 'Resume B' }).click()
  await expect(page.getByRole('status')).toHaveText('Active route within drill limits')
})

test('background updates continue across pages with forecast provenance and separate crew decision', async ({ page }) => {
  await page.clock.install()
  await page.goto(rover)
  await page.getByRole('link', { name: 'Analysis', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Hazard evidence' })).toBeVisible()
  await expect(page.getByRole('table')).toContainText('Learned model')
  await expect(page.getByText('9.08 m/s')).toBeVisible()
  await page.getByRole('button', { name: 'Play drill' }).click()
  await page.getByRole('link', { name: 'Route', exact: true }).click()
  await page.clock.fastForward(10_100)
  await expect(page.getByText('Update 2 / 6')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Approve route B' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Open Monitor to decide' }).click()
  await expect(page.getByRole('button', { name: 'Approve route B' })).toBeEnabled()
  await page.getByRole('button', { name: 'Approve route B' }).click()
  await page.getByRole('button', { name: 'Astronaut', exact: true }).click()
  await expect(route(page, 'A')).toContainText('ACTIVE PLAN')
  await expect(route(page, 'A')).toContainText('GREEN')
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
})

test('bundled replay remains usable offline and fits a narrow viewport', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(rover)
  await context.setOffline(true)
  await next(page)
  await next(page)
  await next(page)
  await expect(page.getByTestId('dust-footprint')).toBeVisible()
  await page.getByRole('checkbox', { name: 'Dust footprint' }).uncheck()
  await expect(page.getByTestId('dust-footprint')).toHaveCount(0)
  await page.getByRole('checkbox', { name: 'Dust footprint' }).check()
  await expect(page.getByTestId('dust-footprint')).toBeVisible()
  await page.getByRole('button', { name: 'Focus routes' }).click()
  await expect(page.getByRole('button', { name: 'Fit terrain' })).toBeVisible()
  await page.getByRole('button', { name: 'Approve route B' }).click()
  await expect(route(page, 'B')).toContainText('ACTIVE PLAN')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  expect(errors).toEqual([])
})

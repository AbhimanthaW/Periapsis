test('the packaged station and hazard API returns six labeled simulated steps', async ({ request }) => {
  for (let step = 0; step < 6; step++) {
    const response = await request.get('/api/v1/hazard-replay/' + step)
    expect(response.status()).toBe(200)
    const frame = await response.json()
    expect(frame.schema_version).toBe(1)
    expect(frame.scenario_id).toBe('marswalk-north-ramp-dust-drill-v1')
    expect(frame.index).toBe(step)
    expect(frame.forecast.status).toBe('issued')
    expect(frame.forecast.model_id).toMatch(/^station-forecast-/)
  }
  expect((await request.get('/api/v1/hazard-replay/6')).status()).toBe(404)
})

test('the globe rotates, switches basemaps and passes its picked cell to the base picker', async ({ page }) => {
  await page.goto('/explore')
  const globe = page.locator('canvas')
  await expect(globe).toBeVisible()
  const box = await globe.boundingBox()
  if (!box) throw new Error('Missing globe')
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width * .75, box.y + box.height / 2, { steps: 8 })
  await page.mouse.up()
  await page.getByRole('button', { name: 'Set base', exact: true }).click()
  const lookup = page.waitForResponse(response => response.url().includes('/api/v1/cell-at'))
  await globe.press('Enter')
  const response = await lookup
  expect(new URL(response.url()).searchParams.get('lon')).not.toBe('0')
  const { id } = await response.json()
  await expect(page.getByRole('heading', { name: id })).toBeVisible()
  await page.getByLabel('Basemap').selectOption('mola')
  await expect(page.getByText(/Candidate base/)).toBeVisible()
  await expect(page).toHaveURL(/base=/)
})

test('selects a different base and uses current crew position to replan to it', async ({ page }) => {
  await page.goto('/explore?demo=1')
  await page.getByRole('button', { name: 'Enter simulated Marswalk' }).click()
  await page.getByLabel('Synthetic base').selectOption('0,2')
  await page.getByRole('button', { name: 'Calculate sortie' }).click()
  await expect(page.getByRole('region', { name: 'Planning result' })).toContainText('science-a')
  await page.getByRole('button', { name: 'Monitor', exact: true }).click()
  await page.getByRole('button', { name: 'Approve route' }).click()
  await page.getByRole('button', { name: 'Record departure' }).click()
  await expect(page.getByLabel('Synthetic base')).toBeDisabled()
  await page.getByLabel('Report simulated crew position').selectOption('1,4')
  await page.getByLabel('Close mid corridor').check()
  await expect(page.getByRole('region', { name: 'Planning result' })).toHaveCount(0)
  const reroute = page.waitForResponse(response => response.url().endsWith('/api/v2/plan'))
  await page.getByRole('button', { name: 'Recalculate return' }).click()
  const response = await reroute
  const plan = await response.json()
  expect(plan.base_cell).toEqual([0, 2])
  expect(plan.current_cell).toEqual([1, 4])
  expect(plan.direct_return.cells.at(-1)).toEqual([0, 2])
  expect(plan.completed_task_ids).toContain('survey-done')
  await expect(page.getByRole('button', { name: 'Approve route' })).toBeEnabled()
})


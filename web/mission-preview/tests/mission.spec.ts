const landmarks = [
  '.objective-panel','.ranking-table','.investigation-panel','.evidence-gallery','.pack-grid',
  '.route-results','.profiles-panel','.compare-dock','.result-gallery','.route-mobile','.task-dock',
  '.eva-timeline','.constraint-gallery','.ranking-analysis','.models-columns','.environment-columns',
  '.report-columns','.record-columns','.rover-monitor','.contingency-dock','.layout-screen',
  '.salvage-panel','.eva-monitor','.eva-tradeoff',
]
states.forEach(([id, ,hash, file, viewport], index) => {
  if(index<3)return // The approved exploration flow captures these three states.
  test('captures reference '+id, async ({page})=>{
    const faults:string[]=[]
    page.on('pageerror', e=>faults.push(e.message))
    page.on('console', e=>{if(e.type()==='error')faults.push(e.text())})
    page.on('response', response=>{if(response.status()>=400)faults.push(response.url())})
    const [width,height]=Array.isArray(viewport)?viewport as number[]:[1440,900]
    await page.setViewportSize({width,height})
    await page.goto('/#'+hash)
    await expect(page.locator(landmarks[index]).first()).toBeVisible()
    await page.evaluate(async()=>{await document.fonts.ready;await Promise.all([...document.images].map(image=>image.decode()))})
    expect(await page.evaluate(()=>[innerWidth,innerHeight,devicePixelRatio,document.documentElement.scrollWidth])).toEqual([width,height,2,width])
    await page.mouse.move(2,height-2)
    await page.screenshot({path:'qa/captures/'+(file||id)+'.png',scale:'device',animations:'disabled'})
    expect(faults).toEqual([])
  })
})
